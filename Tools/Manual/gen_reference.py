def display_name(name: str, is_bool: bool = False) -> str:
    """Same result as the engine's FName::NameToDisplayString, which the editor uses for labels."""
    chars = name
    out: list[str] = []
    in_run = was_space = was_paren = was_number = was_minus = False
    for idx, ch in enumerate(chars):
        lower, upper, digit = ch.islower(), ch.isupper(), ch.isdigit()
        if idx == 0 and is_bool and ch == "b" and len(chars) > 1 and chars[1].isupper():
            continue
        if (upper or (digit and not was_minus)) and not in_run and not was_paren and not was_number:
            if not was_space and out:
                out.append(" ")
                was_space = True
            in_run = True
        if lower:
            in_run = False
        if ch == "_":
            ch = " "
            in_run = True
        if not out:
            ch = ch.upper()
        elif not digit and (was_space or was_paren):
            is_article = False
            for article in ARTICLES:
                length = len(article)
                if idx + length < len(chars) and not chars[idx + length].islower():
                    if chars[idx:idx + length] == article:
                        is_article = True
                        break
            ch = ch.lower() if is_article else ch.upper()
        was_space = ch == " "
        was_paren = ch == "("
        was_minus = ch == "-"
        was_number = digit or (was_number and (was_minus or ch == "."))
        out.append(ch)
    return "".join(out)


