    def ch17_item(self, item: dict) -> str:
        kind = item["kind"]
        if kind == "fn":
            cls, name = item["id"].split(".")
            fn = self.find_func(cls, name)
            return self.function_block(fn, f"fn:{cls}.{name}", anchor=item.get("anchor", ""), owner_label=item.get("target", ""), node=item.get("node", ""))
        if kind == "type":
            cls = item["id"]
            td = self.types[cls]
            title = item.get("title") or td.label
            lines = [f"### {title}" + (f" {{#{item['anchor']}}}" if item.get("anchor") else ""), "", f"[edition: {self.edition('type:' + cls)}]", ""]
            lines += self.doc_blocks(td.doc.summary)
            note = self.note("type:" + cls)
            if note:
                lines += [note, ""]
            props = self.editable_props(cls)
            expand = item.get("expand")
            if expand:
                # Structs shown with their inner fields in place (ShowOnlyInnerProperties).
                expanded = []
                for p in props:
                    if p.name == expand:
                        expanded += self.editable_props(p.type.strip())
                    else:
                        expanded.append(p)
                props = expanded
            if props:
                lines.append(self.prop_table(cls, props))
                lines.append("")
                for block in self.struct_tables(props, cls):
                    lines += [block, ""]
            events = [p for p in self.all_props(cls) if "BlueprintAssignable" in p.flags]
            for e in events:
                sig = self.facts.delegates.get(e.type.strip(), [])
                pins = ", ".join(f"**{display_name(n, t == 'bool')}** ({self.pin_type(t)})" for t, n in sig)
                lines.append(f"Event **{e.label}**" + (f" with {pins}" if pins else "") + f": {sentence(e.doc.text())}")
                lines.append("")
            for fname in item.get("functions", []):
                fn = self.find_func(cls, fname)
                lines.append(self.function_block(fn, f"fn:{cls}.{fname}", heading_level="####", owner_label=item.get("target", td.label)))
            return "\n".join(lines)
        if kind == "enum":
            td = self.types[item["id"]]
            lines = [f"{item.get('lead', '')}", ""]
            for v in td.values:
                lines.append(f"- **{v.label}**: {sentence(v.doc)}")
            lines.append("")
            return "\n".join(lines)
        if kind == "native":
            return self.native_block(item)
        if kind == "note":
            return self.note(item["id"]) + "\n"
        raise SystemExit("unknown ch17 item kind " + kind)

    def native_block(self, item: dict) -> str:
        cls = item["id"]
        td = self.types[cls]
        wanted = item["functions"]
        rows = []
        body = td.body
        for name in wanted:
            m = re.search(r"(/\*\*(?:(?!\*/).)*\*/)\s*((?:static\s+)?[\w<>\*&:, ]+?\b" + name + r"\s*\([^;{]*\)\s*(?:const)?)\s*[;{]", body, re.S)
            if not m:
                raise SystemExit(f"native function {cls}::{name} not found")
            doc = parse_doc(m.group(1)[3:-2], cls + "." + name)
            decl = re.sub(r"\s+", " ", m.group(2)).strip()
            rows.append([f"`{decl}`", sentence(doc.text()), self.edition(f"cpp:{cls}.{name}")])
        for name in item.get("delegates", []):
            m = re.search(r"(\w+)\s+" + name + r"\s*;", body)
            dtype = m.group(1)
            src = strip_line_comments(read_source(td.file))
            dm = re.search(r"/\*\*((?:(?!\*/).)*)\*/\s*DECLARE_MULTICAST_DELEGATE_\w+\(\s*" + dtype + r"\s*,([^;]*)\);", src, re.S)
            doc = parse_doc(dm.group(1), dtype)
            sig = ", ".join(f"{t} {n}" for t, n in self.facts.delegates.get(dtype, []))
            rows.append([f"`{dtype} {name}` ({sig})", sentence(doc.text()), self.edition(f"cpp:{cls}.{name}")])
        return self.table(["Declaration", "What it does", "Edition"], rows, [42, 44, 14]) + "\n"

