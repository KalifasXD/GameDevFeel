def preprocessor_ranges(src: str) -> list[tuple[int, int, str]]:
    ranges, stack = [], []
    for m in re.finditer(r"^[ \t]*#(if|ifdef|ifndef|else|elif|endif)\b(.*)$", src, re.M):
        kind, cond = m.group(1), m.group(2).strip()
        if kind.startswith("if"):
            stack.append((m.end(), cond))
        elif kind in ("else", "elif"):
            if stack:
                start, c = stack.pop()
                ranges.append((start, m.start(), c))
                stack.append((m.end(), "!" + c))
        elif stack:
            start, c = stack.pop()
            ranges.append((start, m.start(), c))
    return ranges


def in_condition(ranges, pos: int, name: str) -> bool:
    return any(s <= pos < e and c == name for s, e, c in ranges)


def parse_decl_name(decl: str) -> tuple[str, str, str | None]:
    eq = find_top(decl, "=")
    default = None
    if eq != -1:
        default = decl[eq + 1:].strip()
        decl = decl[:eq]
    decl = decl.strip()
    m = re.match(r"^(.*?)(\w+)\s*$", decl, re.S)
    return m.group(1).strip(), m.group(2), default


def parse_members(td: TypeDecl, src: str, body_start: int, ranges) -> None:
    body = td.body
    for m in re.finditer(r"\b(UPROPERTY|UFUNCTION)\s*\(", body):
        kind = m.group(1)
        open_at = m.end() - 1
        close_at = skip_to_match(body, open_at, "(", ")")
        flags, meta = parse_specifiers(body[open_at + 1:close_at - 1])
        where = f"{td.name} {body[close_at:close_at + 60].strip()[:40]}"
        doc = parse_doc(doc_before(body, m.start()), where)
        editor_only = in_condition(ranges, body_start + m.start(), "WITH_EDITORONLY_DATA")
        if kind == "UPROPERTY":
            end = find_top(body, ";", close_at)
            ptype, name, default = parse_decl_name(body[close_at:end])
            td.props.append(Prop(name, ptype, default, flags, meta, doc, td.name, editor_only))
        else:
            end = find_top(body, ";{", close_at)
            decl = body[close_at:end].strip()
            paren = decl.index("(")
            head = decl[:paren]
            pclose = skip_to_match(decl, paren, "(", ")")
            args = decl[paren + 1:pclose - 1]
            hm = re.match(r"^(.*?)(\w+)\s*$", head, re.S)
            ret = hm.group(1).replace("virtual", "").strip()
            static = "static" in ret.split()
            ret = ret.replace("static", "").strip()
            params = []
            for a in split_top(args):
                if not a:
                    continue
                pmeta = {}
                um = re.match(r"\s*UPARAM\s*\(", a)
                if um:
                    uclose = skip_to_match(a, um.end() - 1, "(", ")")
                    _, pmeta = parse_specifiers(a[um.end():uclose - 1])
                    if "UPARAM(ref)" in a[:uclose]:
                        pmeta["ref"] = "1"
                    a = a[uclose:]
                ptype, pname, pdefault = parse_decl_name(a)
                params.append(Param(pname, ptype, pdefault, pmeta))
            td.funcs.append(Func(hm.group(2), ret, params, flags, meta, doc, td.name, static))
    for m in re.finditer(r"virtual\s+bool\s+(\w+)\(\)\s*const\s*override\s*\{\s*return\s+(true|false)\s*;\s*\}", body):
        td.inline[m.group(1)] = m.group(2)


def parse_enum_body(td: TypeDecl) -> None:
    pattern = re.compile(r"(?:/\*\*(?P<doc>.*?)\*/\s*)?(?P<name>[A-Za-z_]\w*)\s*(?:=\s*[^,]+?)?\s*(?:UMETA\s*\((?P<umeta>[^)]*)\))?\s*(?:,|\Z)", re.S)
    for m in pattern.finditer(td.body.strip()):
        name = m.group("name")
        label = None
        if m.group("umeta"):
            _, meta = parse_specifiers(m.group("umeta"))
            label = meta.get("__DisplayName")
            if meta.get("Hidden") is not None:
                continue
        doc = clean_text(" ".join(l.strip() for l in doc_lines(m.group("doc") or "") if l.strip()), td.name + "." + name)
        td.values.append(EnumValue(name, label or display_name(name), doc))


def read_source(path: Path) -> str:
    """A source file as FeelKit Pro ships it: the edition marker lines (Tools/Run/make_edition.py) are left out."""
    lines = path.read_text(encoding="utf-8-sig").split("\n")
    return "\n".join(l for l in lines if l.strip() not in ("// FEELKIT_PRO_BEGIN", "// FEELKIT_PRO_END")
                     and not l.strip().startswith("// FEELKIT_LITE:"))


def parse_header(path: Path, types: dict[str, TypeDecl]) -> None:
    raw = read_source(path)
    src = strip_line_comments(raw)
    ranges = preprocessor_ranges(src)
    for m in re.finditer(r"\b(UCLASS|USTRUCT|UENUM|UINTERFACE)\s*\(", src):
        # Skip mentions inside comments.
        line_start = src.rfind("\n", 0, m.start()) + 1
        if src[line_start:m.start()].strip():
            continue
        open_at = m.end() - 1
        close_at = skip_to_match(src, open_at, "(", ")")
        flags, meta = parse_specifiers(src[open_at + 1:close_at - 1])
        dm = re.compile(r"\s*(class|struct|enum\s+class)\s+(?:\w+_API\s+)?(\w+)\s*(?::\s*(?:public\s+)?([\w:]+))?\s*\{", re.S).match(src, close_at)
        if not dm:
            continue
        brace = dm.end() - 1
        body_end = skip_to_match(src, brace, "{", "}")
        kind = {"UCLASS": "class", "USTRUCT": "struct", "UENUM": "enum", "UINTERFACE": "interface"}[m.group(1)]
        name = dm.group(2)
        td = TypeDecl(kind, name, dm.group(3) or "", flags, meta, parse_doc(doc_before(src, m.start()), name), path, src[brace + 1:body_end - 1])
        if kind == "enum":
            parse_enum_body(td)
        else:
            parse_members(td, src, brace + 1, ranges)
        types[name] = td
        if kind == "interface":
            im = re.compile(r"class\s+(?:\w+_API\s+)?(I" + name[1:] + r")\s*\{").search(src, body_end)
            if im:
                ib = im.end() - 1
                iend = skip_to_match(src, ib, "{", "}")
                itd = TypeDecl("iinterface", im.group(1), "", [], {}, td.doc, path, src[ib + 1:iend - 1])
                parse_members(itd, src, ib + 1, ranges)
                types[itd.name] = itd


