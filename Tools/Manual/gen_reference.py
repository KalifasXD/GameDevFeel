@dataclass
class CppFacts:
    channels: dict[str, str] = field(default_factory=dict)       # class -> FeelTags symbol
    preview: dict[str, str] = field(default_factory=dict)        # class -> "true"/"false"
    ctors: dict[str, dict[str, str]] = field(default_factory=dict)
    validation: dict[str, list[tuple[str, str]]] = field(default_factory=dict)
    tags: dict[str, tuple[str, str]] = field(default_factory=dict)  # symbol -> (tag, comment)
    cvars: list[tuple[str, str, str, str]] = field(default_factory=list)
    stats: list[tuple[str, str]] = field(default_factory=list)
    showdebug_category: str = ""
    delegates: dict[str, list[tuple[str, str]]] = field(default_factory=dict)


def function_bodies(src: str, name: str):
    for m in re.finditer(r"(\w+)::" + name + r"\s*\(([^)]*)\)\s*(?:const)?\s*(?::[^{;]*)?\{", src):
        start = m.end() - 1
        end = skip_to_match(src, start, "{", "}")
        yield m.group(1), src[start + 1:end - 1]


def parse_cpp(path: Path, facts: CppFacts) -> None:
    src = strip_line_comments(read_source(path))
    for cls, body in function_bodies(src, "GetDefaultChannel_Implementation"):
        found = re.findall(r"return\s+FeelTags::(\w+)", body)
        if found:
            facts.channels[cls] = found[-1]
    for cls, body in function_bodies(src, "SupportsPreview_Implementation"):
        m = re.search(r"return\s+(true|false)\s*;", body)
        if m:
            facts.preview[cls] = m.group(1)
    for m in re.finditer(r"(\w+)::\1\s*\(\s*\)\s*(?::[^{;]*)?\{", src):
        start = m.end() - 1
        body = src[start + 1:skip_to_match(src, start, "{", "}") - 1]
        values = facts.ctors.setdefault(m.group(1), {})
        for statement in split_top(body, ";"):
            statement = statement.strip()
            sm = re.match(r"^([\w\.]+)\s*=\s*(.+)$", statement, re.S)
            if sm:
                values[sm.group(1)] = sm.group(2).strip()
            elif re.match(r"^\w+\.AddDefaulted\(\)$", statement):
                values[statement.split(".")[0] + ".__AddDefaulted"] = "1"
    for cls, body in function_bodies(src, "ValidateStep"):
        for vm in re.finditer(r"Out(Errors|Warnings)\.Add\(NSLOCTEXT\(\s*\"[^\"]*\"\s*,\s*\"[^\"]*\"\s*,\s*\"((?:[^\"\\]|\\.)*)\"\s*\)\)", body):
            facts.validation.setdefault(cls, []).append(("Error" if vm.group(1) == "Errors" else "Warning", vm.group(2)))
    for tm in re.finditer(r"UE_DEFINE_GAMEPLAY_TAG_COMMENT\(\s*(\w+)\s*,\s*\"([^\"]+)\"\s*,\s*\"((?:[^\"\\]|\\.)*)\"\s*\)", src):
        facts.tags[tm.group(1)] = (tm.group(2), tm.group(3))
    for cm in re.finditer(r"TAutoConsoleVariable<(\w+)>\s+\w+\(\s*TEXT\(\"([^\"]+)\"\)\s*,\s*([^,]+?)\s*,\s*TEXT\(\"((?:[^\"\\]|\\.)*)\"\)", src):
        facts.cvars.append((cm.group(2), cm.group(1), cm.group(3), cm.group(4)))
    for sm in re.finditer(r"DECLARE_(CYCLE_STAT|DWORD_ACCUMULATOR_STAT|STATS_GROUP)\(\s*TEXT\(\"([^\"]+)\"\)", src):
        facts.stats.append((sm.group(1), sm.group(2)))
    dm = re.search(r"static const FName FeelCategory\(TEXT\(\"(\w+)\"\)\)", src)
    if dm:
        facts.showdebug_category = dm.group(1)


def parse_delegates(path: Path, facts: CppFacts) -> None:
    src = strip_line_comments(read_source(path))
    for m in re.finditer(r"DECLARE_(?:DYNAMIC_)?MULTICAST_DELEGATE_\w+\(\s*(\w+)\s*,([^;]*)\);", src):
        parts = [p.strip() for p in split_top(m.group(2))]
        params = []
        if "/*" in m.group(2):
            # Native delegates give only types, with the names in comments.
            for p in parts:
                nm = re.search(r"/\*\s*(\w+)\s*\*/", p)
                params.append((re.sub(r"/\*.*?\*/", "", p).strip(), nm.group(1) if nm else ""))
        else:
            for i in range(0, len(parts) - 1, 2):
                params.append((parts[i], parts[i + 1]))
        facts.delegates[m.group(1)] = params


