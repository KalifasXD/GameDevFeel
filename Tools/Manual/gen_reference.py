class CodeLeak(Exception):
    pass


def clean_text(text: str, where: str = "") -> str:
    """Prepares a source comment for the manual: no internal codes, the real settings path."""
    text = PAREN_CODES_RE.sub("", text)
    text = LEADING_CODE_RE.sub("", text)
    text = re.sub(r"\(\s*\)", "", text)
    text = text.replace("Project Settings > FeelKit >", "Project Settings > Plugins > FeelKit >")
    text = text.replace("Project Settings > FeelKit)", "Project Settings > Plugins > FeelKit)")
    text = re.sub(r"\be\.g\.\s*", "for example ", text)
    for us, uk in US_TO_UK:
        text = re.sub(r"\b" + us + r"\b", uk, text)
    text = re.sub(r"[ \t]+", " ", text).strip()
    text = re.sub(r"\s+([.,;:])(?=\s|$)", r"\1", text)
    if CODE_RE.search(text):
        raise CodeLeak(f"internal code left in text from {where}: {text}")
    return text


def sentence(text: str) -> str:
    text = text.strip()
    if text and text[-1] not in ".!?:":
        text += "."
    return text


