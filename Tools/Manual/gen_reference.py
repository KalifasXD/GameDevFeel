def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
        sys.stderr.reconfigure(encoding="utf-8", errors="replace")
    parser = argparse.ArgumentParser(description="Write the generated reference chapters of the FeelKit Manual.")
    parser.add_argument("--plugin", type=Path, default=DEFAULT_PLUGIN, help="FeelKit plugin folder")
    args = parser.parse_args()
    if not (args.plugin / "FeelKit.uplugin").exists():
        print(f"FeelKit.uplugin not found in {args.plugin}", file=sys.stderr)
        return 1
    overrides = yaml.safe_load((HERE / "overrides.yaml").read_text(encoding="utf-8"))
    ref = Reference(args.plugin, overrides)
    try:
        ref.load()
        chapters = {
            "16_steps.generated.md": ref.chapter16(),
            "17_nodes.generated.md": ref.chapter17(),
            "18_settings.generated.md": ref.chapter18(),
            "19_console.generated.md": ref.chapter19(),
        }
    except CodeLeak as error:
        print(f"Stopped: {error}", file=sys.stderr)
        return 1
    for name, text in chapters.items():
        if CODE_RE.search(text):
            print(f"Stopped: internal code in {name}: {CODE_RE.search(text).group(0)}", file=sys.stderr)
            return 1
        (SRC / name).write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote src/{name}")
    for w in sorted(set(ref.warnings)):
        print("warning:", w)
    for key in sorted(set(ref.unassigned_editions)):
        print("edition not listed in overrides.yaml, marked Pro:", key)
    return 0


if __name__ == "__main__":
    sys.exit(main())
