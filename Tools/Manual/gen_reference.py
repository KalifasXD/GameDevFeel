    # --- loading ---------------------------------------------------------------------------

    def load(self) -> None:
        headers, cpps = [], []
        for base in [self.plugin / "Source", self.plugin / "Extras"]:
            for p in base.rglob("*.h"):
                if "Tests" in p.parts or "Intermediate" in p.parts:
                    continue
                if "Public" in p.parts or p.name in ("FeelEditorSettings.h", "FeelEditorScripting.h"):
                    headers.append(p)
            for p in base.rglob("*.cpp"):
                if "Tests" in p.parts or "Intermediate" in p.parts:
                    continue
                cpps.append(p)
        for h in sorted(headers):
            parse_header(h, self.types)
            parse_delegates(h, self.facts)
        for c in sorted(cpps):
            parse_cpp(c, self.facts)
        for name, td in self.types.items():
            td.ctor = self.facts.ctors.get(name, {})
        for f in sorted(NOTES.glob("*.md")):
            self.load_notes(f)

    def load_notes(self, path: Path) -> None:
        key, lines = None, []
        for line in path.read_text(encoding="utf-8").splitlines():
            if line.startswith("@@ "):
                if key:
                    self.notes[key] = "\n".join(lines).strip()
                key, lines = line[3:].strip(), []
            elif key:
                lines.append(line)
        if key:
            self.notes[key] = "\n".join(lines).strip()

    def note(self, key: str) -> str:
        text = self.notes.get(key, "")
        return text

    # --- type helpers ----------------------------------------------------------------------

    def chain(self, name: str) -> list[TypeDecl]:
        out = []
        while name in self.types:
            td = self.types[name]
            out.append(td)
            name = td.base
        return out

    def is_a(self, name: str, base: str) -> bool:
        return any(td.name == base for td in self.chain(name))

    def all_props(self, name: str) -> list[Prop]:
        props = []
        for td in reversed(self.chain(name)):
            props.extend(td.props)
        return props

    def ctor_value(self, cls: str, prop: str) -> str | None:
        for td in self.chain(cls):
            if prop in td.ctor:
                return td.ctor[prop]
        return None

    def inline_or_cpp(self, cls: str, func: str, default: str) -> str:
        for td in self.chain(cls):
            if func in td.inline:
                return td.inline[func]
            if func == "SupportsPreview_Implementation" and td.name in self.facts.preview:
                return self.facts.preview[td.name]
        return default

    def channel_of(self, cls: str) -> str:
        for td in self.chain(cls):
            if td.name in self.facts.channels:
                return self.facts.tags[self.facts.channels[td.name]][0]
        return ""

    def comfort_group_of(self, tag: str) -> str:
        mapping = self.default_channel_groups()
        best, best_len = None, -1
        for channel, group in mapping:
            if tag == channel or tag.startswith(channel + "."):
                if len(channel) > best_len:
                    best, best_len = group, len(channel)
        return best or ""

    def default_channel_groups(self) -> list[tuple[str, str]]:
        raw = self.types["UFeelSettings"].ctor.get("ChannelComfortGroups", "")
        enum = self.types["EFeelComfortGroup"]
        out = []
        for m in re.finditer(r"FFeelChannelComfortMapping\(\s*FeelTags::(\w+)\s*,\s*EFeelComfortGroup::(\w+)\s*\)", raw):
            out.append((self.facts.tags[m.group(1)][0], self.enum_label(enum, m.group(2))))
        return out

    def enum_label(self, enum: TypeDecl, value: str) -> str:
        for v in enum.values:
            if v.name == value:
                return v.label
        return display_name(value)

    def edition(self, key: str) -> str:
        lite = set(self.ov.get("lite", []))
        if key in lite:
            return "Lite and Pro"
        if key not in set(self.ov.get("pro", [])) and key not in set(self.ov.get("step_order", [])):
            self.unassigned_editions.append(key)
        return "Pro"

    # --- values ------------------------------------------------------------------------------

    @staticmethod
    def number(text: str) -> str | None:
        t = text.strip()
        t = re.sub(r"(?<=\d)[fF]$", "", t)
        try:
            v = float(t)
        except ValueError:
            return None
        if v == int(v) and abs(v) < 1e12:
            return str(int(v))
        return "%g" % v

    def numbers_in(self, text: str) -> list[str]:
        inner = text[text.index("(") + 1:text.rindex(")")]
        return [self.number(x) or x for x in split_top(inner)]

    def format_value(self, ptype: str, raw: str | None, owner: str = "", pname: str = "") -> str:
        key = f"{owner}.{pname}"
        if key in self.ov.get("defaults", {}):
            return self.ov["defaults"][key]
        t = re.sub(r"\bconst\b|&", "", ptype).strip()
        base = t.rstrip("*").strip()
        if raw is not None:
            raw = raw.strip()
        if t == "bool":
            return "On" if raw == "true" else "Off"
        if t in ("float", "double", "int32", "uint8", "int64"):
            if raw is None:
                return "0"
            return self.number(raw) or raw
        if base in self.types and self.types[base].kind == "enum":
            enum = self.types[base]
            if raw is None:
                return enum.values[0].label if enum.values else ""
            return self.enum_label(enum, raw.split("::")[-1])
        if base == "ETriggerEvent" and raw:
            return display_name(raw.split("::")[-1])
        if base in ("FVector", "FVector2D"):
            if raw is None or raw.endswith("ZeroVector"):
                return "(0, 0, 0)" if base == "FVector" else "(0, 0)"
            if raw.endswith("OneVector"):
                return "(1, 1, 1)"
            if raw.endswith("UpVector"):
                return "(0, 0, 1)"
            return "(" + ", ".join(self.numbers_in(raw)) + ")"
        if base == "FRotator":
            if raw is None or "ZeroRotator" in raw:
                return "Pitch 0, Yaw 0, Roll 0"
            p, y, r = self.numbers_in(raw)
            return f"Pitch {p}, Yaw {y}, Roll {r}"
        if base == "FLinearColor":
            if raw is None:
                return "R 0, G 0, B 0, A 0"
            if raw.endswith("::White"):
                return "White (R 1, G 1, B 1)"
            if raw.endswith("::Black"):
                return "Black (R 0, G 0, B 0)"
            nums = self.numbers_in(raw)
            text = f"R {nums[0]}, G {nums[1]}, B {nums[2]}"
            if len(nums) > 3 and nums[3] != "1":
                text += f", A {nums[3]}"
            return text
        if base == "FFloatInterval" and raw:
            lo, hi = self.numbers_in(raw)
            return f"Min {lo}, Max {hi}"
        if base in ("FName",):
            if raw is None or raw in ("NAME_None", "FName()"):
                return "None"
            m = re.search(r'"(.*)"', raw)
            return f"`{m.group(1)}`" if m else raw
        if base in ("FString",):
            if raw is None:
                return "empty"
            m = re.search(r'"(.*)"', raw)
            return f"`{m.group(1)}`" if m else raw
        if base == "FText":
            if raw is None:
                return "empty"
            m = re.search(r'LOCTEXT\(\s*"[^"]*"\s*,\s*"((?:[^"\\]|\\.)*)"\s*\)', raw)
            return f'"{m.group(1)}"' if m else raw
        if base == "FGameplayTag":
            return "None"
        if base == "FGameplayTagContainer":
            return "empty"
        if re.match(r"^(TArray|TMap|TSet)<", base):
            return "empty"
        if re.match(r"^(TObjectPtr|TSoftObjectPtr|TSoftClassPtr|TSubclassOf|TWeakObjectPtr|TScriptInterface)<", base) or base in ("FSoftObjectPath",) or t.endswith("*"):
            return "None"
        if base in self.types and self.types[base].kind == "struct":
            return "see below"
        if raw is not None:
            return raw
        self.warnings.append(f"no default format for {owner}.{pname} ({ptype})")
        return ""

    def units(self, prop: Prop, owner: str) -> str:
        key = f"{owner}.{prop.name}"
        extra = self.ov.get("units", {})
        if key in extra:
            return extra[key]
        if f"{prop.owner}.{prop.name}" in extra:
            return extra[f"{prop.owner}.{prop.name}"]
        return UNITS.get(prop.meta.get("Units", ""), "")

    def with_units(self, value: str, unit: str) -> str:
        if not unit or value in ("", "None", "empty"):
            return value
        if unit in ("°", "°/s"):
            if re.match(r"^-?[\d.]+$", value):
                return value + unit
            return value + " (degrees)"
        return f"{value} {unit}"

    def prop_default(self, prop: Prop, owner: str) -> str:
        raw = self.ctor_value(owner, prop.name)
        if raw is None:
            raw = prop.default
        key = f"{owner}.{prop.name}"
        if key in self.ov.get("defaults", {}):
            return self.ov["defaults"][key]
        value = self.format_value(prop.type, raw, prop.owner, prop.name)
        return self.with_units(value, self.units(prop, owner))

    def condition_text(self, prop: Prop, siblings: list[Prop]) -> str:
        cond = prop.meta.get("EditCondition")
        if not cond:
            return ""
        by_name = {p.name: p for p in siblings}
        parts = []
        for clause in re.split(r"\s*&&\s*", cond):
            clause = clause.strip()
            m = re.match(r"^(!?)(\w+)$", clause)
            if m:
                p = by_name.get(m.group(2))
                label = p.label if p else display_name(m.group(2), True)
                parts.append(f"**{label}** is {'off' if m.group(1) else 'on'}")
                continue
            m = re.match(r"^(\w+)\s*(==|!=|>|<|>=|<=)\s*(.+)$", clause)
            if not m:
                self.warnings.append(f"edit condition not translated: {cond}")
                return ""
            p = by_name.get(m.group(1))
            label = p.label if p else display_name(m.group(1))
            rhs = m.group(3).strip()
            if rhs == "nullptr":
                value = "empty"
                op = {"==": "is", "!=": "is not"}[m.group(2)]
                parts.append(f"**{label}** {op} {value}")
                continue
            if "::" in rhs:
                enum_name, value_name = rhs.split("::")
                enum = self.types.get(enum_name)
                value = self.enum_label(enum, value_name) if enum else display_name(value_name)
                value = f"**{value}**"
            else:
                value = self.number(rhs) or rhs
            op = {"==": "is", "!=": "is not", ">": "is above", "<": "is below", ">=": "is at least", "<=": "is at most"}[m.group(2)]
            parts.append(f"**{label}** {op} {value}")
        verb = "Shown only when" if "EditConditionHides" in prop.meta else "Editable only when"
        return f"{verb} " + " and ".join(parts) + "."

    def range_text(self, prop: Prop) -> str:
        lo, hi = prop.meta.get("ClampMin"), prop.meta.get("ClampMax")
        lo = self.number(lo) if lo else None
        hi = self.number(hi) if hi else None
        if lo is not None and hi is not None:
            return f"Range {lo} to {hi}."
        if lo is not None:
            return f"At least {lo}."
        if hi is not None:
            return f"At most {hi}."
        return ""

    def prop_description(self, prop: Prop, owner: str, siblings: list[Prop]) -> str:
        key = f"{owner}.{prop.name}"
        text = " ".join(b[2:] if b.startswith("- ") else b for b in prop.doc.summary)
        text = self.ov.get("descriptions", {}).get(key, self.ov.get("descriptions", {}).get(f"{prop.owner}.{prop.name}", text))
        text = sentence(text) if text else ""
        extra = [self.range_text(prop), self.condition_text(prop, siblings)]
        if "VisibleAnywhere" in prop.flags:
            extra.append("Read only.")
        if prop.editor_only:
            extra.append("Editor only: not included in packaged games.")
        if "AdvancedDisplay" in prop.flags:
            extra.append("Under the advanced arrow of its category.")
        if prop.editor_only:
            text = text.replace(" Not included in cooked builds.", "")
        lead = "**Pro.**" if f"{prop.owner}.{prop.name}" in set(self.ov.get("pro_fields", [])) else ""
        text = " ".join(x for x in [lead, text] + extra if x)
        return text

    # --- Markdown building blocks -----------------------------------------------------------

    @staticmethod
    def cell(text: str) -> str:
        return text.replace("|", "\\|").replace("\n", " ")

    def prop_rows(self, props: list[Prop], owner: str, siblings: list[Prop] | None = None, prefix: str = "") -> list[list[str]]:
        rows = []
        siblings = siblings if siblings is not None else props
        for p in props:
            rows.append([f"**{prefix}{p.label}**", self.prop_default(p, owner), self.prop_description(p, owner, siblings)])
        return rows

    def table(self, header: list[str], rows: list[list[str]], widths: list[int] | None = None) -> str:
        lines = []
        if widths:
            lines.append("{widths: " + ",".join(str(w) for w in widths) + "}")
        lines.append("| " + " | ".join(header) + " |")
        lines.append("|" + "|".join("---" for _ in header) + "|")
        for r in rows:
            lines.append("| " + " | ".join(self.cell(c) for c in r) + " |")
        return "\n".join(lines)

    def editable_props(self, cls: str, skip: set[str] | None = None, own_only: bool = False) -> list[Prop]:
        skip = skip or set()
        hidden = set(self.ov.get("hidden", []))
        props = self.types[cls].props if own_only else self.all_props(cls)
        return [p for p in props if p.editable and p.name not in skip and f"{p.owner}.{p.name}" not in hidden
                and "BlueprintAssignable" not in p.flags]

    def prop_table(self, cls: str, props: list[Prop], owner: str | None = None) -> str:
        owner = owner or cls
        categories = []
        for p in props:
            if p.category not in categories:
                categories.append(p.category)
        rows = []
        for cat in categories:
            group = [p for p in props if p.category == cat]
            if len(categories) > 1:
                rows.append([">> " + (cat.replace("|", " > ") or "Other"), "", ""])
            rows.extend(self.prop_rows(group, owner, props))
        return self.table(["Property", "Default", "Description"], rows, [26, 20, 54])

    def struct_tables(self, props: list[Prop], owner: str) -> list[str]:
        """Sub-tables for array and struct properties whose element type is a FeelKit struct."""
        out = []
        for p in props:
            m = re.match(r"^TArray<\s*(F\w+)\s*>$", p.type.strip())
            inner = m.group(1) if m else None
            if not inner and p.type.strip() in self.types and self.types[p.type.strip()].kind == "struct":
                inner = p.type.strip()
            if not inner or inner not in self.types or f"{owner}.{p.name}" in set(self.ov.get("no_subtable", [])):
                continue
            sub = self.editable_props(inner)
            if not sub:
                continue
            what = "Each entry of" if m else "The fields of"
            out.append(f"{what} **{p.label}**:")
            out.append(self.table(["Field", "Default", "Description"], self.prop_rows(sub, inner), [26, 20, 54]))
        return out

    # --- function nodes -----------------------------------------------------------------------

    def pin_type(self, t: str) -> str:
        t = re.sub(r"UPARAM\(.*?\)", "", t)
        t = re.sub(r"\bconst\b|&", "", t).strip()
        pointer = t.endswith("*")
        t = t.rstrip("*").strip()
        m = re.match(r"TScriptInterface<I(\w+)>", t)
        if m:
            return display_name(m.group(1)) + " (interface)"
        simple = {"float": "Float", "double": "Float", "int32": "Integer", "bool": "Boolean", "FName": "Name",
                  "FString": "String", "FText": "Text", "FVector": "Vector", "FGameplayTag": "Gameplay Tag",
                  "FGameplayTagContainer": "Gameplay Tag Container", "UObject": "Object", "AActor": "Actor"}
        if t in simple:
            return simple[t] + (" (object)" if pointer and t not in ("UObject", "AActor") else "")
        if pointer and t[:1] in "UA":
            return display_name(t[1:])
        if t[:1] in "FE":
            return display_name(t[1:])
        return t

    def pin_default(self, param: Param) -> str:
        if param.default is None:
            return ""
        return self.format_value(param.type, param.default)

    def function_block(self, fn: Func, key: str, heading_level: str = "###", anchor: str = "", owner_label: str = "", node: str = "") -> str:
        lines = [f"{heading_level} {fn.label}" + (f" {{#{anchor}}}" if anchor else ""), ""]
        lines.append(f"[edition: {self.edition(key)}]")
        lines.append("")
        lines += self.doc_blocks(fn.doc.summary)
        note = self.note(key)
        if note:
            lines += [note, ""]
        pure = "BlueprintPure" in fn.flags
        kind = "Pure node, no execution pins" if pure else "Callable node with execution pins"
        if fn.meta.get("BlueprintInternalUseOnly") == "true":
            kind = "Latent node with an output execution pin for each outcome"
        facts = [f"- **Node:** {node or kind}."]
        if owner_label:
            facts.append(f"- **Target:** {owner_label}.")
        facts.append(f"- **Category:** {fn.meta.get('__Category', '').replace('|', ' > ')}.")
        facts.append(f"- **C++:** `{fn.owner}::{fn.name}`.")
        lines += facts + [""]
        world = fn.meta.get("WorldContext")
        auto_ref = set(x.strip() for x in fn.meta.get("AutoCreateRefTerm", "").split(",") if x.strip())
        advanced = set(x.strip() for x in fn.meta.get("AdvancedDisplay", "").split(",") if x.strip())
        rows = []
        for p in fn.params:
            if p.name == world:
                continue
            desc = fn.doc.params.get(p.name, "")
            desc = sentence(desc) if desc else ""
            if p.name in auto_ref:
                desc += " Can be left unconnected."
            if p.name in advanced:
                desc += " Shown under the node's advanced arrow."
            direction = "Out" if p.is_out else "In"
            rows.append([f"**{display_name(p.name, p.is_bool)}**", direction, self.pin_type(p.type), self.pin_default(p), desc.strip()])
        if kind.startswith("latent"):
            for e in [p for p in self.types[fn.owner].props if "BlueprintAssignable" in p.flags]:
                rows.append([f"**{e.label}**", "Out", "Execution", "", sentence(e.doc.text())])
            sig = []
            for e in [p for p in self.types[fn.owner].props if "BlueprintAssignable" in p.flags][:1]:
                sig = self.facts.delegates.get(e.type.strip(), [])
            for t, n in sig:
                rows.append([f"**{display_name(n)}**", "Out", self.pin_type(t), "", "Handle of the play, set when either output fires."])
        elif fn.ret and fn.ret != "void":
            rows.append(["**Return Value**", "Out", self.pin_type(fn.ret), "", sentence(fn.doc.returns) if fn.doc.returns else ""])
        if rows:
            lines.append(self.table(["Pin", "In or out", "Type", "Default", "Description"], rows, [20, 9, 17, 11, 43]))
            lines.append("")
        return "\n".join(lines)

    @staticmethod
    def doc_blocks(blocks: list[str]) -> list[str]:
        lines = []
        for i, block in enumerate(blocks):
            lines.append(block)
            is_item = block.startswith("- ")
            next_is_item = i + 1 < len(blocks) and blocks[i + 1].startswith("- ")
            if not (is_item and next_is_item):
                lines.append("")
        return lines

    def find_func(self, cls: str, name: str) -> Func:
        for f in self.types[cls].funcs:
            if f.name == name:
                return f
        raise KeyError(f"{cls}.{name}")

